    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try
        {
            
            //Declare my variables
           String Product = jComboBoxBed.getSelectedItem().toString();
           String customerName = txtCustomerName.getText();
           
           Double price = Double.parseDouble(txtPrice.getText());
           //Price declarations and Calculations
           Double VAT = price * 0.15;
           Double Comm = price * 0.05;
           Double Total = price + VAT + Comm;
           
           //output into the Text Area
           txtReport.setText(
                   "\nCustomer Name" + customerName +
                           "\nProduct" + Product + 
                           "\nVAT R" + VAT + 
                           "\nCOMMISSION " + Comm + 
                           "\nTOTAL " + Total );
           
           JOptionPane.showMessageDialog(this,"Processed Successfully");
            
        }catch(NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this,"Error,Process unsuccessful");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

